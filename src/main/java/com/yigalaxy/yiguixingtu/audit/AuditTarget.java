package com.yigalaxy.yiguixingtu.audit;

/**
 * 审计的"操作对象类型" —— 这件事是被做在什么东西上的。
 *
 * 【为什么 action 里已经带了对象名（CREATE_ARTICLE），还要单独一个枚举】
 *   两者回答的是不同的问题，用途也不同：
 *     · action 回答"做了什么"，主要是给人看的（页面上直接显示"新建文章"）
 *     · target 回答"做在什么上"，是给【按对象查询】用的：
 *       "这个用户被改动过几次" = 按 target_type + target_id 查，
 *       而不是拿 action 去 LIKE '%USER%' 猜名字
 *   而且 target 是有限且稳定的（文章、用户、标签、评论、分类）：新增一类"被操作的对象"
 *   只是在这里多一个取值，不用再往 action 的命名里塞前缀约定。
 *   —— 这条预判已经兑现过一次：分类的增 / 改 / 删接进审计时，这个枚举只多了一行
 *   {@code CATEGORY}，三个 action 也照原有命名加上 CREATE/UPDATE/DELETE 前缀即可。
 */
public enum AuditTarget {

    /** 文章 */
    ARTICLE,

    /** 用户 */
    USER,

    /** 标签 */
    TAG,

    /** 评论 */
    COMMENT,

    /** 分类 */
    CATEGORY,

    /**
     * 友链。
     *
     * 【这里只加一行，和上次加分类时的情况一样】
     *   这个枚举当初就是为了"新增一类被操作的对象只是多一行"而拆出来的
     *   （见类注释里那段预判）。F5 的四个内容模块（友链 / 项目 / 收藏 / 关于）
     *   正好又是一次验证：action 那边按既有命名加 3 个前缀，这边加 1 个取值，
     *   不用动任何已有的代码与数据。
     */
    LINK,

    /**
     * 项目。
     * 和 LINK 一样只是多一行 —— 这个枚举的设计目的（新增一类被操作的对象
     * 不需要改动任何已有代码与数据）在这里第二次得到验证。
     */
    PROJECT,

    /**
     * 收藏。
     * 到这里 F5 的四个内容模块已经有三个进了审计（LINK / PROJECT / FAVORITE），
     * 每个模块在这个枚举里就是一行 —— 这正是把"操作对象类型"单独拆成枚举的价值。
     */
    FAVORITE,

    /**
     * 关于页。
     *
     * 【它和另外三个内容模块的一个差别】友链 / 项目 / 收藏的 target_id 是"某一条数据的 id"，
     * 而关于页只有一份数据，target_id 恒为 1 —— 所以按 target_type = 'ABOUT' 查
     * 就能直接得到"关于页被谁改过几次"的完整历史（连 id 条件都不用加）。
     */
    ABOUT
}
