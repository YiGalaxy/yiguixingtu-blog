package com.yigalaxy.yiguixingtu.upload;

import java.io.InputStream;

/**
 * =====================================================================
 * 文件存储的抽象接口 —— "把一段内容存到一个 key 上，并返回可访问的 URL"
 *
 * 【为什么要抽这一层，而不是让 UploadService 直接写文件】
 *   因为"存哪里"是会变的东西，而上传的其余部分（类型白名单、大小限制、
 *   重命名、按年月分目录）跟"存哪里"完全无关：
 *     · 现在：写服务器本地磁盘（见 {@link LocalFileStorage}）
 *     · 将来图片多到磁盘吃紧、或者要上多台机器做负载均衡时：
 *       换成对象存储（OSS / S3 / MinIO），本地磁盘在每台机器上各自独立，
 *       多实例下用户上传的图在另一台就看不到了
 *   抽一层接口之后，业务只依赖"能存、能返回一个可直接放进 &lt;img src&gt; 的地址"
 *   这个契约，换存储时 UploadService 一行都不用改。
 *
 * 【它算不算"自研轮子"】
 *   不算，而且这一层是有意保留的**唯一**一处抽象。
 *   这里没有自己实现任何存储能力（没有手写 HTTP 上传、没有自己算签名），
 *   真接上对象存储时那部分完全交给官方 SDK；这一层只是【依赖倒置】。
 *
 * 【⚠️ 为什么现在只有一个实现，却还留着接口】
 *   "只有一个实现就删掉接口"是常见的简化，但这里不适用：
 *   存储位置恰恰是那种【几乎一定会变】、而且变的时候最不想动业务代码的东西
 *   （换存储要动 UploadService 的构造、参数、返回值，还要重跑全部上传用例）。
 *   反过来，项目早期那套 `OssFileStorage` 是**真删掉了** ——
 *   它的存在需要一堆密钥配置、依赖与"两条代码路径"，而这条路径没人走过、
 *   也没法在 CI 里验证（需要真实凭据与公网）。留着没人用的实现不是扩展性，
 *   是负担：多一份要跟着改的代码、多一条"配错了但没人发现"的路。
 *   真要接对象存储时，照着这个接口写一个新的实现 + 它自己的配置项即可。
 * =====================================================================
 */
public interface FileStorage {

    /**
     * 保存一个文件。
     *
     * ============================================================
     * 【⚠️ 参数为什么是 InputStream 而不是 byte[]】
     * ============================================================
     *   附件上限是 100MB（见 {@link UploadProperties#getAttachmentMaxSize()}）。
     *   接口如果收 byte[]，调用方就必须【先把整个文件读进堆】才能调它 ——
     *   而容器内存上限 640m、堆约 384MB
     *   （见 docker-compose.prod.yaml 的 mem_limit 与那里的 JAVA_TOOL_OPTIONS），
     *   三四个并发的大附件上传就足以把容器打 OOM。症状是"上传到一半服务没了"，
     *   而且日志里看不出跟上传有关。
     *   收流之后，整条链路（MultipartFile → 这里 → 磁盘）是流式拷贝，
     *   堆占用与文件大小无关，只跟缓冲区大小有关。
     *
     * 【流的关闭责任在调用方，实现方不要关】
     *   调用方用 try-with-resources 管着这个流；实现里再关一次就成了二次关闭
     *   （有的流实现在二次关闭时会抛异常）。所以实现只负责"把它读完"。
     *
     * @param content     文件内容流。大小限制的校验【不在这里做】——
     *                    UploadService 已经按类型校验过（图片 10MB / 音频 20MB / 附件 100MB）
     * @param objectKey   对象在存储里的唯一路径，形如 {@code cover/2026/09/xxxx.jpg}。
     *                    由调用方（UploadService）统一生成，
     *                    这样"文件放在哪"这件事对存储实现是透明的
     * @param contentType 文件的 MIME 类型，例如 image/png。
     *                    浏览器靠它决定"打开时是显示还是下载"，
     *                    不传或传错的话图片会变成下载文件
     * @return 可以直接放进 &lt;img src&gt; 的完整 URL
     */
    String store(InputStream content, String objectKey, String contentType);

    /**
     * 删除一个已保存的文件（文章被删除、或编辑文章时移除了某个附件时用）。
     *
     * 【为什么"删除"属于存储抽象的一部分，而不是在业务代码里直接 Files.delete】
     *   与 store 是同一条理由：业务层只该知道"有一个对象、它的 key 是什么"，
     *   不该知道它是磁盘上的一个文件还是对象存储里的一个 object。
     *   把它放进接口还有一个额外好处：**将来加对象存储实现时，
     *   编译器会强制实现者想一遍"删除怎么做"** —— 如果删除只写在
     *   LocalFileStorage 里，换存储时那几行会被静默地落下，
     *   表现是"删了文章、OSS 上的文件永远留着"，而且不会有任何报错。
     *
     * 【为什么是"删了就算了"而不是抛异常】
     *   文件不存在（已经被删过、或者根本没写成功）是【正常的幂等情形】：
     *   删除的语义是"让它不存在"，本来就不存在也算达成。
     *   真正删不掉（没权限、目录被占用）时会记日志并抛运行时异常，
     *   由调用方决定怎么处理 —— 但见 ArticleServiceImpl 里的做法：
     *   级联清理发生在【业务事务提交之后】，那时候再抛异常也没人能补救，
     *   所以那里会自己兜住异常，只留日志（文件清理失败不该回滚一次已经成功的删除）。
     *
     * @param objectKey 对象在存储里的路径，形如 {@code attachment/2026/09/xxxx.pdf}
     */
    void delete(String objectKey);

    /**
     * 存储里已经占用的字节数（用于上传总量护栏，见 {@link UploadProperties#getMaxTotalSize()}）。
     *
     * 【为什么让存储实现自己回答这个问题】
     *   "还剩多少空间"只有存储自己最清楚：本地磁盘要遍历目录，
     *   对象存储要么调用量接口、要么自己记账 —— 业务层不该替它猜。
     *
     * ⚠️ 【换了对象存储之后这个方法的实现必须重新想一遍】
     *   这正是把它放进接口的价值：本地磁盘上遍历目录是毫秒级的，
     *   而对象存储"列出全部对象再求和"是又慢又贵的一次 API 调用 ——
     *   那种情况下正确的做法是"上传时累加到一个计数器里"（Redis/数据库），
     *   而不是每次上传都去枚举一遍 bucket。把这条写在这里，
     *   免得将来实现者照着本地磁盘的写法抄一遍，然后在生产上把
     *   对象存储的请求配额打满。
     *
     * @return 已占用的字节数；目录还不存在（从没上传过）时返回 0
     */
    long usedBytes();
}
