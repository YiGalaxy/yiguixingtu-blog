-- =====================================================================
-- V12 · 站点设置表（site_setting）—— 全站第二张【只有一行】的表
--
-- 【它存什么】
--   "站点怎么运行"这几个开关：站点名 / 首页公告 / 评论总开关 / 页脚版权 /
--   ICP 备案号 / 每页文章条数。
--   在这之前它们全都【写死在前端代码里】：改一个站点名要改五处 .vue、
--   再重新构建部署；而"备案号"这种东西又必须能随时改（换域名、换主体）。
--
-- =====================================================================
-- 【为什么和 about 分两张表，而不是塞进 about 一行里】
--   两张都是"只有一行"，看起来可以合并，但它们的性质不同：
--     · about    = "站长是谁" —— 对外展示的内容，几个月不动一次
--     · 这张表   = "站点怎么运行" —— 配置，上线当天就可能要改好几轮
--   分表的实际收益是【接口形状】：about 是"读一整个关于页"，
--   这里的每个字段各自驱动界面上一处很不一样的东西（页脚、评论开关、分页大小）。
--   混在一张表里之后，about 的读写都会被塞进一堆与"站长是谁"无关的字段，
--   而缓存的失效范围也会变得说不清 —— 改个每页条数不该让关于页缓存重建。
--
-- 【与 about 同形的三处（理由完全一样，不再重复）】
--   · id 固定为 1，实体上用 IdType.INPUT（"主键由我给"，不依赖自增回填）
--   · 只有 update_time，没有 create_time（单条记录没有"创建"这个语义）
--   · 没有 deleted / 逻辑删除（"删掉站点设置"这个需求不存在：不要了就改回默认值）
--   代价与兜底同样一致：万一那一行被手工删了，公开的 GET 返回一份【内置默认值】
--   （页面照常打开），后台点一次保存会把它自愈地写回来 —— 见 SettingServiceImpl。
--
-- 【迁移里直接插入那一行，而且初始值 = 前端此刻写死的那些值】
--   这一条很关键：它的目的是让"上线这个功能"本身【不改变站点外观】。
--   如果种子值编一个别的站点名，那么部署完打开首页会发现站名变了 ——
--   而正确的预期是"什么都没变，只是以后可以在后台改了"。
--   所以：
--     · site_name 填前端 seo.ts 里 SITE_NAME 的当前值
--     · page_size 填文章接口的默认每页条数（10）
--     · comment_enabled 填 1（现在评论是开着的）
--     · announcement / copyright / icp_number 留【空】——
--       它们在前端现在【本来就没有对应元素】，留空 = 不显示 = 外观不变。
--       ⚠️ 尤其 icp_number 不预填：备案号是站点主体相关的信息，
--       该由站长在后台自己填（而且它属于"备案材料"，不该出现在公开仓库的迁移脚本里）。
-- =====================================================================

CREATE TABLE `site_setting` (
  -- 固定为 1：这张表永远只有这一行
  `id`              bigint       NOT NULL COMMENT '固定为 1（这张表只有一行）',
  `site_name`       varchar(50)  NOT NULL COMMENT '站点名（标题后缀 / 页眉页脚 / og:site_name）',
  -- 首页公告：留空表示不显示。上限 500 字是"一句话通知"的量级 ——
  -- 真要写长文应该去发一篇文章，而不是塞在公告条里
  `announcement`    varchar(500) DEFAULT NULL COMMENT '首页公告（为空则不显示）',
  -- 评论总开关：0 关闭 1 开启。tinyint 与其它表的 status 字段同形（DEFAULT 1）
  `comment_enabled` tinyint      NOT NULL DEFAULT '1' COMMENT '评论总开关：0关闭 1开启',
  -- ICP 备案号：只存号本身，【不存链接】—— 链接是固定的 beian.miit.gov.cn，
  -- 由前端写死。让用户填 URL 只会多出一种"填错/填成别处"的可能
  `icp_number`      varchar(50)  DEFAULT NULL COMMENT 'ICP 备案号（为空则不显示备案信息）',
  -- 页脚版权：比如 "© 2026 亿轨星途"。留空则页脚不显示版权行
  `copyright`       varchar(200) DEFAULT NULL COMMENT '页脚版权文案（为空则不显示）',
  -- 每页文章条数。
  -- ⚠️ 它的上限【必须】跟着文章接口的分页上限走（ArticleQuery.MAX_PAGE_SIZE = 50）：
  --    接口那边超出会被静默夹到 50，如果这里允许填 100，
  --    站长会得到一个"设置了但不生效"的开关，而且不会有任何报错
  --
  -- 【⚠️ 默认值 12 不是随手写的，也不能改成 10】
  --   它是【前端首页此刻真正在用的每页条数】（app/pages/index.vue 里那个 SIZE = 12，
  --   注释写着"3 列瀑布流正好 4 行"）。种子值必须等于它，否则这个功能一上线，
  --   首页就会从 12 篇变成别的数量 —— 而"上线不改变站点外观"是这张表种子值的
  --   全部意义（见文件开头）。
  --   ⚠️ 特别注意它【不是】ArticleQuery.DEFAULT_PAGE_SIZE（10）：
  --      那个 10 的语义是"调用方没传 size 时接口用什么"，和"站点每页显示几篇"
  --      是两件事，只是数字上容易被当成同一个。前端一直是显式传 size 的。
  `page_size`       int          NOT NULL DEFAULT '12' COMMENT '每页文章条数（1~50）',
  -- 只有 update_time，没有 create_time / deleted（理由见文件开头）
  `update_time`     datetime     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='站点设置（全表只有一行）';

-- 建表的同时把那一行插进去（与 V10 的 about 同一个做法）：
-- 让"单条记录"这个不变量由 schema 保证，而不是靠"代码在启动时补一行"——
-- 启动期写库在并发 / 多实例下很容易写出第二行。
--
-- 初始值逐项说明（每一项都等于"前端此刻的表现"）：
--   site_name       = '亿轨星途'   前端 seo.ts 的 SITE_NAME 与页眉页脚上写的就是它
--   comment_enabled = 1            评论现在是开着的
--   page_size       = 12           前端首页的 SIZE = 12（理由见上面那一大段）
--   其余三列留 NULL = 前端不渲染（公告条 / 备案号 / 版权行现在本来就没有对应元素）
INSERT INTO `site_setting` (`id`, `site_name`, `comment_enabled`, `page_size`)
VALUES (1, '亿轨星途', 1, 12);
