-- =====================================================================
-- V13 · 给站点设置（site_setting）加一列：公安网安备案号
--
-- 【加的是什么】
--   中国大陆的网站在页脚上除了工信部的 ICP 备案号，还必须展示
--   【公安网安备案号】和它的备案图标（"公安部全国互联网安全管理服务平台"
--   要求网站在底部悬挂图标与编号）。两个号分别长成
--   "省简称 + ICP备 + 一串数字 + 号-序号" 与
--   "省简称 + 公网安备 + 一串纯数字 + 号" 这两种样子。
--   在这之前 site_setting 只有 icp_number，公安那一行【四个层都没有】——
--   数据库没列、接口没有字段、后台没有输入框、前端没有渲染位置。
--   ⚠️ 这个脚本里【不出现任何真实的备案号】（连举例都用文字描述形式）：
--      理由与下面"为什么不做种子值"是同一条 —— 它是站点主体相关的备案材料，
--      不该进公开仓库。真实的号由站长在后台填。
--
-- =====================================================================
-- 【为什么公安备案要【单独一列】，而不是复用 icp_number】
--   两个号看着都是"备案号"，但它们是【两套完全不同的备案体系】：
--     · 发证 / 主管机关不同：ICP 是工信部（省通信管理局初审），
--       公安备案是公安机关（属地网安部门）。两者【互不替代】——
--       有 ICP 不代表做过公安备案，反之亦然，两个都必须在页脚出现
--     · 编号规则不同：ICP 是"省简称 + ICP备 + 数字 + 号-序号"，
--       公安是"省简称 + 公网安备 + 一串纯数字 + 号"，两串数字的位数都不一样
--     · ⚠️ 最要紧的是【链接规则不同】：页脚上这两个号都要做成可点击的链接，
--       而它们指向的站点是两个：
--         - ICP  → https://beian.miit.gov.cn/（前端写死的固定地址）
--         - 公安 → https://beian.mps.gov.cn/ 上的备案查询页（图标也来自那里）
--       如果两个号挤在同一个字段里（比如拼成 "ICP号；公安号" 存一列），
--       前端就拿不到"哪一段该链到哪个站"这个信息 —— 只能靠解析字符串猜，
--       一旦号里多一个空格或换行，链接就会拼错或者整块不渲染。
--       所以这里存【两个独立的列】，让"两个号各自是什么"由结构表达，
--       而不是由前端解析一段拼接文本得出。
--
-- 【为什么列名叫 police_number，而不是 beian_number】
--   beian_number 这个名字在【只有它一列】的时候是清楚的，但它旁边就躺着
--   icp_number —— 两个名字放在一起时，读者看到 beian_number 根本不知道
--   它是"另一种备案"还是"ICP 备案的另一种写法/别名"。
--   命名要能回答"它和隔壁那一列差在哪"：
--     · icp_number    = 工信部 ICP 备案号
--     · police_number = 公安机关（网安）备案号
--   police 直接指向"公安"这个发证机关，一眼能读出区别；
--   用 beian_number 的话，将来真要再加一种备案（比如某些省份的
--   "网络经营许可"）就没有名字可用了。
--   ⚠️ 与之配套的 Java 侧命名是 policeNumber（见 SiteSetting / SettingForm /
--      SettingVO），保持"列名 = 字段名的下划线 ↔ 驼峰形式"这条 MyBatis-Plus
--      的默认映射约定 —— 一旦两边不照应，就要靠 @TableField 手写映射来补。
--
-- 【为什么【不做种子值】（没有 UPDATE、也没有改 V12 的那条 INSERT）】
--   与 V12 里 icp_number / copyright / announcement 留空的理由【完全一样】，
--   只是这里更强调一层：
--     · 备案号是【站点主体相关的信息】：它绑定的是"哪个主体、在哪个省、
--       备的哪个域名"，没有一个可以当默认值的通用值 —— 编一个出来，
--       等于让某个真实存在的备案号出现在别人的站点页脚上
--     · 它属于站长的【备案材料】：迁移脚本进公开仓库，把真实的备案号写进
--       脚本就等于把站点主体的信息提交进了版本历史。而 V12 那条 INSERT
--       之所以只填 site_name / comment_enabled / page_size，正是因为
--       这三项不是主体相关信息、又必须等于"前端此刻的表现"
--       （见 V12 里"上线这个功能本身不改变站点外观"那一段）
--     · 页脚外观不变：这一列留 NULL = 前端不渲染公安那一行，
--       与上线前完全一致。站长在后台填上之后它才会出现 ——
--       流程见 SettingServiceImpl 的 normalizeOptional 与 toVO
--   ⚠️ 所以【不要】在这里补一条 UPDATE site_setting SET police_number = '<真实号>'：
--      那样既污染公开仓库，又会让"页脚多出一行"变成部署的副作用。
--
-- 【为什么长度是 50（与 icp_number 一致）】
--   · 实际形态的长度：一个公安号在 20 个字符上下
--     （省简称 2 + "公网安备" 4 + 一串 14 位左右的数字 + "号" 1 + 可能的一个空格），
--     50 已经有 2 倍以上余量
--   · 与 icp_number 取同一个值，是为了让两个"备案号"列在结构上完全同形：
--     前端一个输入框的 maxlength、后台一条 @Size 校验、库里一个列宽，
--     三处都能用同一句话解释，不必记"这个 50、那个 60"
--   · 不用更长：备案号是"一行页脚文字"，不是长文本；列宽给大了不会报错，
--     只会让"填错成了别的什么东西"（比如把整段说明粘进来）更容易通过校验
--
-- 【为什么不需要 ALGORITHM / LOCK 提示】
--   与 V2 / V3 那两条加索引的迁移不同，这条 DDL 面向的是一张
--   【全表只有一行】的配置表：任何实现方式的重建都是微秒级，
--   加 ALGORITHM=INSTANT / LOCK=NONE 只是把一个不存在的代价写进脚本。
--   （V3 那次是 10 万行的 article，才需要用 INSTANT/INPLACE 的显式声明
--     把"这次 DDL 会不会锁表"变成可讨论的问题。）
--
-- 【这一列只存号本身，不存链接】
--   与 icp_number 同一条规则：段里存的是 "川公网安备 51090002000169号" 这串字符，
--   【不是】"https://beian.mps.gov.cn/#/query/..." 这样的 URL。
--   理由与 V12 里那段一样 —— 链接是固定的、由前端按平台规则拼，
--   让站长填 URL 只会多出一种"填错/填成别处"的可能（而页脚的备案链接是合规项，
--   填错等于没备案）。实体字段上的 Javadoc 把这条写得更细。
--
-- 【AFTER icp_number 的位置说明】
--   表里的列顺序不影响任何查询（SQL 都是按列名读写的），
--   但物理上挨着放有两个实际好处：
--     · 用 SQL 手工核对时 `SELECT * FROM site_setting` 一眼能看到两个备案号并排，
--       而不是一个在中间、一个在最后
--     · 与前端页脚那几行、与 DTO 里两个字段的先后顺序保持一致 ——
--       四层（库 / 实体 / 接口 / 前端）读起来是同一个顺序，改的时候不容易漏
-- =====================================================================

ALTER TABLE `site_setting`
    ADD COLUMN `police_number` varchar(50) DEFAULT NULL
        COMMENT '公安网安备案号（为空则不显示公安备案信息）'
        AFTER `icp_number`;
