-- =====================================================================
-- V14 · 文章附件表（article_attachment）
--
-- 【它存什么】
--   一篇文章挂的"可下载文件"：论文 PDF、素材压缩包、示例表格、演示视频……
--   每条记录 = 一个文件（名字 + 地址 + 大小），一篇文章可以有 0~20 条。
--
-- =====================================================================
-- 【① 为什么附件要【单独一张表】，而不是在 article 上加一列】
--
--   最省事的改法是在 article 上加一列 attachment_url，甚至把多个地址用逗号
--   拼成一列（project.tech 那种做法）。这里不这么做，理由有两条，且都很具体：
--
--   · 数量是【一对多】，不是一对一：一篇文章挂几个附件是常态（论文 + 数据 + 代码）。
--     拼成逗号串之后，"每篇文章最多几个"就只能靠字符串长度间接限制，
--     而且每个附件都要带 name/size（前端要渲染"文件名 + 大小"的列表），
--     于是这一列得存 "名字|地址|大小,名字|地址|大小" 这种自造格式 ——
--     一旦哪个文件名里出现分隔符，整份数据就解析错了，且没有任何报错。
--     拆成一行一个附件之后，"有几个附件"就是 SELECT COUNT(*)，
--     "删掉其中一个"就是 DELETE 一行，不需要读写整个字符串再拼回去。
--   · 附件是【结构化的字段集合】（name / url / size 三个字段各有含义与校验），
--     不是一段展示文本。项目里唯一的"逗号串"先例是 project.tech，
--     它成立的原因写在 V8 注释 ③ 里：只用于展示、没有按它筛选或统计的需求。
--     附件不符合那两个前提 —— 按 url 反查"这个文件还有没有别处在用"
--     正是删文章时要做的判断（见 V14 之后 ArticleServiceImpl 的级联注释）。
--
--   ⚠️ 与 article_tag 的对比：那张表是纯关联（只有两个 id + 时间），
--   所以它连实体类都没有、直接用联合主键。附件不是关联表 ——
--   它自己带三个业务字段，所以它有自增主键和自己的实体/Mapper。
--
-- =====================================================================
-- 【② 为什么【不在上传时就往这张表插一行】—— 这是本表最关键的一条】
--
--   上传是 POST /upload，保存文章是 POST /admin/article，是【两次独立请求】。
--   用户先传附件、拿到 url，再点"保存"。如果在 /upload 成功时就往这里插一行：
--
--   · 新建文章时【还没有 article_id】。id 是保存那一刻由数据库自增生成的
--     （见 ArticleServiceImpl.create 的注释：MyBatis-Plus 在 insert 之后才回填），
--     上传发生在它之前 —— 那时的 article_id 只能是 NULL 或一个瞎填的值。
--     于是这张表里会出现一堆【悬空记录】：没有文章认领它们，
--     而它们既不会显示在任何一个页面上，也不会被任何一次删除清掉，
--     只能靠人工 SQL 去认。这正是"孤儿数据"最典型的产生方式。
--   · 用户传完附件之后【放弃保存】（关掉页面、断网、点取消）也会留下同样的孤儿行 ——
--     而这件事在上传时是【无法判断】的：那一刻我们根本不知道他会不会保存。
--
--   ⇒ 所以附件走的是"随表单提交、保存时整体替换"的路线（和 tagIds 完全一致）：
--     请求体里带 attachments: [{name, url, size}]，保存文章时先删掉这篇文章的
--     全部旧附件行，再按提交的列表插入。好处是"库里有什么"永远等于
--     "编辑界面上看着有什么"，不需要任何后台清理任务去兜底。
--
--   ⚠️ 代价要说清楚：上传成功但没保存的文件会留在磁盘上（没有行指向它）。
--      这类"孤儿文件"只能靠运维按目录清理 —— 与 music 那条"删歌不删文件"
--      是同一类取舍（见 Music 实体的注释）。宁可有孤儿文件，
--      也不要库里出现指向不存在文章的附件行：前者只占点磁盘，
--      后者会让后续每一次查询/删除都要先判空、且判不干净。
--
-- =====================================================================
-- 【③ 为什么删除文章时要【连物理文件一起删】（而 music 是刻意不删的）】
--
--   music 表的注释写着"删歌只删数据库行、磁盘上的 mp3 不删"，理由是
--   "同一个文件可能被多条记录引用，而删文件不可逆"。附件这里【反过来】做，
--   因为它面临的问题正好相反 —— 附件文件是【一次性】的：
--
--   · 附件的 URL 由我们自己生成（uploads/attachment/yyyy/MM/{uuid}.{ext}），
--     文件名是 UUID，等于"这一个文件只可能被这一次上传产生"。
--     没有"两条记录指向同一个文件"的自然来源。
--   · 而"+100MB 的单文件 × 20 条 × 不断编辑"会让磁盘只涨不落：
--     用户传错一个大文件、改成别的、再传一次，前一个就永远留在盘上 ——
--     删文章时再不清理，uploads 目录就成了只进不出的垃圾桶。
--   · ⚠️ 但"删文件不可逆"这条顾虑仍然成立，所以删除【不是无脑删】：
--     Service 里在删任何一个物理文件之前，都会先查"还有没有别的文章在用它"
--     （附件行 / 正文引用 / 封面，三种引用都查），只有确认没有任何引用才真删。
--     判断方式与完整推导见 ArticleServiceImpl.remove 的中文注释，
--     以及 ArticleAttachmentTest 里那条"共用的图不会被误删"的用例（★）。
--
-- =====================================================================
-- 【④ 与项目既有约定的对齐（逐条说明，避免"自己发明一套"）】
--
--   · 主键：`id` bigint NOT NULL AUTO_INCREMENT —— 与 V5~V12 所有表一致，
--     实体上对应 @TableId(type = IdType.AUTO)
--   · 时间列：只有 `create_time` datetime DEFAULT CURRENT_TIMESTAMP，
--     【没有 update_time】—— 和 article_tag 同一个理由（见 V5）：
--     这一行从插入那一刻起就再也不会被改，"整体替换"在实现上就是
--     "删掉旧行 + 插入新行"，所以"更新时间"这个语义在这张表上不存在。
--     少一列不是省事，是【不给一个永远等于 create_time 的列留位置】。
--   · 【没有 deleted（逻辑删除）】—— 与 article_tag 同一条理由：
--     逻辑删除和"整体替换"直接冲突。替换时要删的是"这次没提交的那些"，
--     如果它们只是被标成 deleted = 1，那么"这篇文章此刻有哪些附件"
--     就必须处处带上 deleted = 0 才成立；漏一处（比如手写 SQL、
--     或者将来有人按 url 反查引用）就会把已经移除的附件又算进来。
--     而附件没有"删错了要恢复"的分量：重新上传一次即可（文件是 UUID 命名，
--     恢复一行反而指向一个可能已经被清理掉的文件）。
--     判断标准与 V5/V6 的取舍说明一致：这张表【没有任何唯一索引】，
--     所以逻辑删除不会踩"唯一索引被幽灵行占着"那个坑 ——
--     也就是说，这里是【可以选择】逻辑删除而主动不选，理由就是上面这条。
--   · 【没有外键】—— 与全项目一致（V5 末尾那一段讲得最清楚）：
--     引用完整性由 Service 一处实现，不用数据库的隐式级联。
--     这里尤其不能有外键：article 用的是【逻辑删除】（删文章只把 deleted 置 1，
--     物理行还在），外键的 ON DELETE CASCADE 根本不会触发 ——
--     一个看起来会级联、实际永远不动手的外键，比没有外键危险得多。
--   · 索引：`idx_article` (article_id) —— 两个方向都要用它：
--     ① 详情页按文章查附件（SELECT ... WHERE article_id = ?）
--     ② 删文章时按文章删附件行（DELETE ... WHERE article_id = ?）
--     没有它两处都是全表扫描。不带 status/时间之类的第二列：
--     这张表没有"按状态筛"或"按时间排序"的查询，
--     多写的列只会让索引变大、且给人一种"已经优化过"的错觉。
--     ⚠️ 这里【刻意不给 url 建索引】：级联删除时要用
--     LOCATE(url 片段, url) 去反查"还有谁在用这个文件"，
--     而函数/LIKE 前置通配符的匹配走不了 B+ 树索引
--     （同 README「为什么没有给 title 建索引」那一条）。
--     附件表的量级是"文章数 × 20 以内"，这种查询扫全表也就是几毫秒。
--   · 列长度：name varchar(100)（与 ArticleForm 的 @Size(max = 100) 一致）、
--     url varchar(255)（与 article.cover、music.url 等所有 URL 列一致）。
--     三处（库列 / DTO 校验 / 前端输入框）取同一个数字，改的时候不容易漏一处。
--   · size bigint —— 存【字节数】。用 int 也放得下 100MB（int 上限约 2.1GB），
--     但一旦哪天把上限放宽到 2GB 以上，int 会静默溢出成负数，
--     而字节数用 bigint 是通行做法，多出的 4 字节在这个量级毫无意义。
--     前端要显示的是"12.3 MB"这种文本，格式化成什么由前端决定 ——
--     库里存原始字节数，避免"这一列到底存的是 MB 还是 KB"这种歧义。
-- =====================================================================

CREATE TABLE `article_attachment` (
  `id`          bigint       NOT NULL AUTO_INCREMENT COMMENT '附件ID',
  `article_id`  bigint       NOT NULL COMMENT '所属文章ID',
  -- 附件名（用户上传时的原始文件名，去掉路径、截断到 100 字）
  -- ⚠️ 它是【展示用的文本】，不参与任何路径拼接：磁盘上的真名是 UUID
  `name`        varchar(100) NOT NULL COMMENT '附件显示名（上传时的原始文件名）',
  -- 附件地址：形如 {base-url}/uploads/attachment/2026/09/{uuid}.pdf
  -- 只接受本项目上传地址前缀之内的 url，由 ArticleServiceImpl 校验
  -- （防止有人把外部地址塞进来：那会变成"在自己的站点上挂别人的钓鱼文件"）
  `url`         varchar(255) NOT NULL COMMENT '附件地址（本项目上传目录内的 URL）',
  -- 文件大小（字节）。上限由 app.upload.attachment-max-size 控制（默认 100MB）
  `size`        bigint       NOT NULL COMMENT '文件大小（字节）',
  -- 只有 create_time，没有 update_time（理由见上面 ④）
  `create_time` datetime     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间（附件随文章保存的时间）',
  PRIMARY KEY (`id`),
  -- 详情页按文章查附件 / 删文章时按文章删附件行，两个方向都靠它（理由见上面 ④）
  KEY `idx_article` (`article_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='文章附件表';

-- 【不插任何种子数据】附件是"作者自己传的文件"，编几条假数据进迁移脚本，
-- 上线后第一件事就是一条条删掉 —— 与 V8（项目）/ V11（音乐）同一个取舍。
