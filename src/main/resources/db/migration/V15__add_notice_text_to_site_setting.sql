-- =====================================================================
-- V15：给 site_setting 加一列「首页滚动文字」
--
-- 【它是干什么的】首页顶部那条滚动的跑马灯。
--   在这之前那句话是【硬编码在前端源码里】的（index.vue 的 .notice 块），
--   站长想改一个字都得改代码、重新构建前端镜像 —— 这是首页上最后一处
--   写死的、而站长明显会想改的文案。加到设置里之后它与其他文案同一个待遇：
--   后台改完即时生效（走 PUT /admin/setting 的缓存版本号作废）。
--
-- 【和 announcement（首页公告）是什么关系 —— 说清楚，免得被当成重复】
--   两条都在首页顶部，但是【两块不同的东西】：
--     · announcement 是一条静态公告（不滚动），来自接口，出现时机由站长控制
--     · notice_text  是那条一直滚动的跑马灯，属于站点装饰
--   前端不合并它们的理由写在 index.vue 的模板注释里（公告为空时跑马灯照样在滚）。
--   合并成一列的话，"只想留公告、不想要跑马灯"就表达不出来了。
--
-- 【⚠️ 为什么放在 copyright 之后，而不是 police_number 之后】
--   SiteSettingTest 有一条断言：police_number 的 ORDINAL_POSITION 必须
--   【恰好等于】icp_number 的 +1（它守着"公安备案号要挨着 ICP 备案号"这个
--   可读性约定）。把新列插在两个备案号中间会让那条断言变红 ——
--   而这并不是它的错，是插入位置的问题。放在 copyright 后面既安全，
--   语义上也合适（都是"页脚/首页上的一段展示文案"）。
--
-- 【为什么不写种子值（与 V13 加 police_number 那次同一个选择）】
--   留 NULL = 前台不渲染那条跑马灯。上线后首页会先没有它，
--   站长到后台填上才出现 —— 这是刻意选的默认值：一句话的文案属于站点主人的
--   表达，由他自己决定要不要说，而不是由迁移脚本替他决定。
--   （前端在 noticeText 为 null 时整块不渲染，与 announcement 同一套语义。）
-- =====================================================================

ALTER TABLE `site_setting`
    ADD COLUMN `notice_text` varchar(200) DEFAULT NULL
        COMMENT '首页滚动文字（为空则不显示那条跑马灯）'
        AFTER `copyright`;
