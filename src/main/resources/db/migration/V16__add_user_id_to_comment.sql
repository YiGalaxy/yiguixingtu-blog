-- =====================================================================
-- V16：给 comment 加一列 user_id（这条评论是哪个【注册账号】发的）
--
-- 【为什么需要它】在这之前 comment 表里只有 nickname —— 一个**用户手填的字符串**。
--   于是两件事都做不到：
--     · 后台审核时看不出"这是注册用户发的"还是"游客随手填了个一样的名字"；
--       也就是说任何人都能冒用站长的昵称发评论，而系统里没有任何依据能分辨
--     · 注册用户发的评论与账号之间没有关联，将来想按人查（"这个账号都说过什么"）
--       或者想做"注册用户免审核"之类的区分时，没有任何东西可以 join
--   加一列之后：注册用户发的评论带上账号 id，游客仍然是 NULL。
--
-- 【为什么允许 NULL，而不是 NOT NULL + 外键】
--   ① 游客评论是【常态】（这个站允许匿名评论，只填昵称就能发），
--      它们的 user_id 天然为空 —— 一列"大多数行都是空"的外键没有意义
--   ② 本项目不用外键（见 V5 迁移脚本里的说明），一致性由应用层保证
--   ③ 账号被逻辑删除之后，这条评论仍然要能显示（评论是内容，不该跟着账号消失）——
--      外键会逼着我们在"删账号"和"保评论"之间二选一
--
-- 【为什么不加索引】目前没有任何按 user_id 查询的路径（后台列表按状态筛、
--   前台按文章筛，两条都有自己的索引）。将来真要做"按用户查评论"时再加 ——
--   加索引的理由应当来自一条真实的查询，而不是"以后可能会用"。
--
-- 【历史数据怎么办】已有的评论全部留 NULL。它们确实无法追溯是谁发的
--   （那时后端根本不读 token，没有任何信息可回溯）—— 这不需要"猜"，
--   下面的注释也写给了将来看到这列全是 NULL 的人。
-- =====================================================================

ALTER TABLE `comment`
    ADD COLUMN `user_id` bigint DEFAULT NULL
        COMMENT '评论者的注册账号 id（游客为 NULL；2026-09 之前的评论一律为 NULL）'
        AFTER `article_id`;
