-- V18：给 user 加一列 email（注册时必填）
--
-- 【为什么现在加】在这之前注册只要用户名 + 密码（昵称都只是选填），
--   于是站长手里【没有任何】联系注册用户的方式 —— 将来要做找回密码、
--   要给用户发通知，第一步都是"先拿到一个能发信过去的地址"。
--   现在把它变成注册的必填项，是让这件事从"以后再说"变成"从第一条记录起就有"。
--
-- 【为什么允许 NULL，而不是 NOT NULL】
--   因为**存量用户没有邮箱**，而且不可能凭空补一个 ——
--   要么强迫他们下次登录时补填（那是另一套"资料不完整"的流程，本期不做），
--   要么就只能让这一列空着。给非空默认值更糟：`''` 会被后面的
--   "邮箱格式校验"判成非法值，而 `'unknown@example.com'` 是编造数据。
--   ⇒ 所以：**数据库列可空，必填由 RegisterRequest 上的 @NotBlank 保证**。
--     `email IS NULL` 这一种情况有且只有一个来源：这一列存在之前注册的老账号。
--
-- 【为什么不加唯一索引】
--   本期**不发验证邮件**（不引 SMTP、没有验证码环节）。也就是说
--   "这个邮箱真的是他的"这件事从来没有被验证过 ——
--   一个没被验证过的值不能当身份键：
--     · 加唯一索引之后，"别人先填了你的邮箱"会变成一个新的、用户
--       完全无法理解的注册失败原因（他自己的邮箱为什么不能用？）
--     · 它还挡不住真正的重复：同一个人用 `a+x@qq.com` 和 `a@qq.com`
--       注册两个号，唯一索引一点用都没有
--   ⇒ 等哪天真的上了邮箱验证，再加唯一索引（那时它才有意义）。
--
-- 【长度为什么是 100】与 comment.email、about.email 保持一致 ——
--   同一个概念在本项目里只有一个长度，将来做"从邮箱反查"时不用先对齐口径。
-- =====================================================================

ALTER TABLE `user`
    ADD COLUMN `email` varchar(100) DEFAULT NULL
        COMMENT '邮箱（注册必填；NULL = 本列存在之前注册的老账号，无法追溯）'
        AFTER `nickname`;
