-- V19：给 visit_log 加一列 region（IP 归属地）
--
-- 【它解决什么问题】后台「访问统计」原来只能看到聚合数字（PV/UV/构成），
--   表里明明存着每一条的 ip，但界面上看不到 ——
--   想回答"是不是同一个人在刷""访客都从哪来"只能连数据库。
--   加一个下钻的访客 IP 列表时，光有一串 IP 帮助有限
--   （`223.5.5.5` 和 `116.25.100.1` 对人来说是两串没有意义的数字），
--   标出"浙江杭州""广东深圳"才看得出分布。
--
-- 【为什么写入时就解析落库，而不是读的时候现算】
--   与这张表已有的 device（从 UA 推导）、referer_type（从 Referer 推导）
--   是同一个套路：**原始串不入库，推导结果入库**。
--   好处是列表接口一条 GROUP BY 就出结果，不用对每一行再查一次库；
--   将来想做"按地区看构成"时也已经有了现成的列。
--   代价是解析库升级后老行的归属地不会跟着变 —— 对"看趋势"这个用途无所谓。
--
-- ⚠️ 【region 和 ip 一样是个人信息，所以生命周期必须和 ip 完全一致】
--   它是从 IP 推导出来的，颗粒度到城市 —— 保留期到期时**随记录一起删**
--   （VisitLogCleanupTask 删的是整行，不需要为它单独做清理）。
--   千万别把它当成"脱敏后的安全字段"：知道某人 2026-09-20 在深圳市，
--   和知道他的 IP，对定位一个人的帮助没有量级上的差别。
--
-- 【为什么允许 NULL】新增这一列之前的历史记录没有归属地。
--   它们不需要一次性回填（回填要写一个一次性的迁移工具，而收益只是
--   "历史行的列表里多显示一个城市"）—— 读的时候按需解析即可，
--   **只读、不写回**，见 VisitLogServiceImpl.visitorIps。
--   另外解析失败（内网地址、IPv6、畸形值）时也是 NULL。
--
-- 【长度为什么是 64】解析结果最多是"省 市"这种十来字的组合，
--   但解析库更新后可能变成更长的一串。64 比实际需要宽裕，
--   与列宽留余量的习惯一致（ip 列同样给到 64）。
-- =====================================================================

ALTER TABLE `visit_log`
    ADD COLUMN `region` varchar(64) DEFAULT NULL
        COMMENT 'IP 归属地（写入时从 ip 推导；NULL = 本列存在前的历史记录或解析不出）'
        AFTER `ip`;
